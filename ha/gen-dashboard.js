'use strict';
// Generate the Home Assistant template sensors + Lovelace dashboard for the spa.
//
//   node gen-dashboard.js sim  > out-sim.yaml
//   node gen-dashboard.js real > out-real.yaml
//
// Why templates at all: everything on the wire is Celsius (deliberately — a
// fixed unit_of_measurement with a value that changes unit is a bug). But the
// spa has its own display scale, and the dashboard should follow *that*, not
// Home Assistant's global unit system. So we publish °C, derive °F, and let a
// conditional card pick which to show based on select.*_temperature_scale.

const TARGETS = {
  // Device name comes from esphome friendly_name ("Hot Tub"); entities are
  // named "Spa", "Spa Light"... so HA yields hot_tub_spa, hot_tub_spa_light.
  real: { slug: 'hot_tub_spa', title: 'Hot Tub' },
  sim:  { slug: 'balboa_spa_simulated_spa_sim', title: 'Spa (Simulated)' },
};
const which = process.argv[2] || 'sim';
const T = TARGETS[which];
if (!T) { console.error('usage: gen-dashboard.js [real|sim] [entity_id_prefix]'); process.exit(1); }
// HA derives entity_ids from the device + entity names, and prefixes the device
// name when has_entity_name is set. Pass the real prefix rather than guessing:
//   Developer Tools > States, filter "spa" — use the part before the last name.
const S = process.argv[3] || T.slug;

// Entity ids HA derives from the MQTT entity names. Verify against your device;
// HA appends _2 etc. on name collisions.
const E = {
  climate: `climate.${S}`,
  jets: `fan.${S}_jets`,
  light: `switch.${S}_light`,
  hold: `switch.${S}_hold`,
  mode: `select.${S}_heating_mode`,
  range: `select.${S}_temperature_range`,
  scale: `select.${S}_temperature_scale`,
  curTemp: `sensor.${S}_current_temperature`,
  tgtTemp: `sensor.${S}_target_temperature`,
  model: `sensor.${S}_model`,
  firmware: `sensor.${S}_firmware_version`,
  notification: `sensor.${S}_notification`,
  heating: `binary_sensor.${S}_heating`,
  priming: `binary_sensor.${S}_priming`,
  filterRunning: `binary_sensor.${S}_filter_cycle_1_running`,
  circ: `binary_sensor.${S}_circulation_pump`,
  bus: `binary_sensor.${S}_bus_connected`,
  filterStart: `number.${S}_filter_1_start_hour`,
  filterDur: `number.${S}_filter_1_duration`,
  clearNotif: `button.${S}_clear_notification`,
  normalOp: `button.${S}_normal_operation`,
};

// HA derives a template sensor's entity_id from its NAME, not from the MQTT
// prefix — so compute both from one place or they drift apart.
const slug = (t) => t.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
const FNAME_CUR = `${T.title} Current Temperature F`;
const FNAME_TGT = `${T.title} Target Temperature F`;
const F_CUR = `sensor.${slug(FNAME_CUR)}`;
const F_TGT = `sensor.${slug(FNAME_TGT)}`;

// Jinja helper: current/target rendered in the spa's own scale, with unit.
const disp = (ent) =>
  `{% set v = states('${ent}') | float(0) %}` +
  `{% if is_state('${E.scale}', 'celsius') %}` +
  `{{ v | round(1) }} °C{% else %}{{ (v * 9 / 5 + 32) | round(1) }} °F{% endif %}`;

console.log(`# =============================================================================
# ${T.title} — generated by ha/gen-dashboard.js (${which})
#
# PART 1 goes in configuration.yaml (merge into your existing top-level keys).
# PART 2 is the Lovelace dashboard: Settings > Dashboards > new dashboard,
#        then three-dot menu > "Raw configuration editor" and paste.
#
# Entity ids assume HA derived them from the MQTT names. If HA appended
# suffixes (_2 etc.), adjust the ids at the top of this file and regenerate.
# =============================================================================


# ----------------------------- PART 1: configuration.yaml --------------------
# Fahrenheit companions. The wire is always Celsius; these derive °F with a
# FIXED unit, which is safe. Never publish a value whose unit varies at runtime.

template:
  - sensor:
      - name: "${FNAME_CUR}"
        unique_id: ${S}_current_temperature_f
        unit_of_measurement: "°F"
        device_class: temperature
        state_class: measurement
        availability: "{{ states('${E.curTemp}') not in ['unknown','unavailable',''] }}"
        state: "{{ (states('${E.curTemp}') | float * 9 / 5 + 32) | round(1) }}"

      - name: "${FNAME_TGT}"
        unique_id: ${S}_target_temperature_f
        unit_of_measurement: "°F"
        device_class: temperature
        state_class: measurement
        availability: "{{ states('${E.tgtTemp}') not in ['unknown','unavailable',''] }}"
        state: "{{ (states('${E.tgtTemp}') | float * 9 / 5 + 32) | round(1) }}"


# ----------------------------- PART 2: Lovelace dashboard --------------------
views:
  - title: ${T.title}
    path: ${S}
    icon: mdi:hot-tub
    cards:

      # --- Bus/availability warning. Only appears when something is wrong, so
      # --- a healthy dashboard stays clean.
      - type: conditional
        conditions:
          - entity: ${E.bus}
            state_not: "on"
        card:
          type: markdown
          content: >
            ## ⚠️ Spa unreachable

            The gateway is not receiving data from the spa over RS-485.
            **Values below are the last known readings and may be stale.**

      # --- Headline instrument: temperatures in the SPA's own scale ---
      - type: markdown
        content: >
          # ${disp(E.curTemp)}

          ### Set to ${disp(E.tgtTemp)}

          {% if is_state('${E.heating}', 'on') %}🔥 **Heating**
          {% elif is_state('${E.mode}', 'rest') %}💤 Rest mode — heater disabled
          {% else %}✓ Idle — at temperature{% endif %}
          {% if is_state('${E.filterRunning}', 'on') %} · 🌀 Filtering{% endif %}
          {% if states('${E.notification}') not in ['', 'unknown', 'unavailable'] %}

          ⚠️ Notification: **{{ states('${E.notification}') }}**
          {% endif %}

      # --- Gauge, shown in whichever scale the spa is using ---
      - type: conditional
        conditions:
          - entity: ${E.scale}
            state: fahrenheit
        card:
          type: gauge
          entity: ${F_CUR}
          name: Water
          min: 50
          max: 106
          needle: true
          severity: { green: 98, yellow: 80, red: 104 }
      - type: conditional
        conditions:
          - entity: ${E.scale}
            state: celsius
        card:
          type: gauge
          entity: ${E.curTemp}
          name: Water
          min: 10
          max: 41
          needle: true
          severity: { green: 36, yellow: 26, red: 40 }

      # --- Setpoint control ---
      - type: thermostat
        entity: ${E.climate}
        features:
          - type: target-temperature

      # --- Everyday controls ---
      - type: grid
        columns: 2
        square: false
        cards:
          - type: tile
            entity: ${E.light}
            name: Light
            icon: mdi:lightbulb
          - type: tile
            entity: ${E.jets}
            name: Jets
            icon: mdi:chart-bubble
            features:
              - type: fan-speed
          - type: tile
            entity: ${E.mode}
            name: Mode
            icon: mdi:thermostat
            features:
              - type: select-options
          - type: tile
            entity: ${E.range}
            name: Range
            icon: mdi:thermometer-lines
            features:
              - type: select-options

      # --- Status at a glance ---
      - type: entities
        title: Status
        show_header_toggle: false
        entities:
          - entity: ${E.bus}
            name: Spa link
          - entity: ${E.heating}
            name: Heater
          - entity: ${E.circ}
            name: Circulation pump
          - entity: ${E.filterRunning}
            name: Filter cycle
          - entity: ${E.priming}
            name: Priming
          - entity: ${E.hold}
            name: Hold

      # --- Filter schedule + maintenance ---
      - type: entities
        title: Filter cycle
        show_header_toggle: false
        entities:
          - entity: ${E.filterStart}
            name: Start hour
          - entity: ${E.filterDur}
            name: Duration
          - type: divider
          - entity: ${E.clearNotif}
            name: Clear notification
          - entity: ${E.normalOp}
            name: Normal operation

      # --- Diagnostics, collapsed by default ---
      - type: entities
        title: Diagnostics
        show_header_toggle: false
        entities:
          - entity: ${E.model}
            name: Model
          - entity: ${E.firmware}
            name: Firmware
          - entity: ${E.scale}
            name: Panel scale
          - entity: ${E.curTemp}
            name: Water (raw °C)
          - entity: ${E.tgtTemp}
            name: Setpoint (raw °C)
`);
